const norm = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();

export const GENERIC_FOODS: Food[] = ROWS.map(([name, kcal, protein, carbs, fat, serving], i) => ({
  id: "taco-" + i,
  name,
  brand: null,
  image: null,
  kcal,
  protein,
  carbs,
  fat,
  servingG: serving,
  source: "Tabela TACO",
}));

/** Generic foods whose name matches every typed word (word-prefix, accent-insensitive). */
export function searchGeneric(q: string): Food[] {
  const tokens = norm(q).split(/[^a-z0-9]+/).filter(Boolean);
  if (!tokens.length) return [];
  return GENERIC_FOODS.filter((f) => {
    const words = norm(f.name).split(/[^a-z0-9]+/);
    return tokens.every((t) => words.some((w) => w.startsWith(t)));
  });
}
